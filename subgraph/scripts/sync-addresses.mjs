// graph-contracts-sync: pull deployed addresses from the core repo's deployments JSON into
// networks.json (used by `graph build --network sepolia`) and src/addresses.ts (used by the
// mappings). Start blocks are kept unless START_BLOCK=<n> is set (use the redeploy block).
//
//   CORE_REPO=… CHAIN_ID=11155111 NETWORK=sepolia node scripts/sync-addresses.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const CORE = process.env.CORE_REPO ?? join(here, "../../../rwa-outlet-contracts-core");
const CHAIN_ID = process.env.CHAIN_ID ?? "11155111";
const NETWORK = process.env.NETWORK ?? "sepolia";
const START_BLOCK = process.env.START_BLOCK ? Number(process.env.START_BLOCK) : undefined;

const dep = JSON.parse(readFileSync(join(CORE, "deployments", `${CHAIN_ID}.json`), "utf8"));

// dataSource name in subgraph.yaml -> key in deployments/<chainid>.json
const DATA_SOURCES = {
  Aqua: "Aqua",
  AquaSwapVMRouter: "AquaSwapVMRouter",
  NavOracle: "NavOracle",
  NavExtruction: "NavExtruction",
  ComplianceNFT: "ComplianceNFT",
  OutletRouter: "OutletRouter",
  RedemptionQueueTbill: "RedemptionQueue_rwaTBILL",
  RedemptionQueueCredit: "RedemptionQueue_rwaCREDIT",
  CuratorVaultExpress: "CuratorVault_Express",
  CuratorVaultPatient: "CuratorVault_Patient",
  RWAGateHook: "RWAGateHook",
  TestUSDC: "TestUSDC",
  RwaTbillToken: "rwaTBILL",
  RwaCreditToken: "rwaCREDIT",
  Faucet: "Faucet",
};

const networksPath = join(here, "../networks.json");
const networks = JSON.parse(readFileSync(networksPath, "utf8"));
networks[NETWORK] ??= {};
for (const [ds, key] of Object.entries(DATA_SOURCES)) {
  if (!dep[key]) throw new Error(`deployments JSON is missing "${key}"`);
  networks[NETWORK][ds] = {
    address: dep[key],
    startBlock: START_BLOCK ?? networks[NETWORK][ds]?.startBlock ?? 0,
  };
}
writeFileSync(networksPath, JSON.stringify(networks, null, 2) + "\n");
console.log(`networks.json updated for "${NETWORK}" from deployments/${CHAIN_ID}.json`);

// Address constants for the mappings (lowercase — mappings compare lowercased hex).
const lc = (k) => dep[k].toLowerCase();
const ts = `// AUTO-GENERATED by scripts/sync-addresses.mjs from
// rwa-outlet-contracts-core/deployments/${CHAIN_ID}.json — do not edit by hand.
export const AQUA = "${lc("Aqua")}";
export const SWAP_VM = "${lc("AquaSwapVMRouter")}";
export const NAV_ORACLE = "${lc("NavOracle")}";
export const NAV_EXTRUCTION = "${lc("NavExtruction")}";
export const COMPLIANCE_NFT = "${lc("ComplianceNFT")}";
export const OUTLET_ROUTER = "${lc("OutletRouter")}";
export const USDC = "${lc("TestUSDC")}";
export const RWA_TBILL = "${lc("rwaTBILL")}";
export const RWA_CREDIT = "${lc("rwaCREDIT")}";
export const QUEUE_TBILL = "${lc("RedemptionQueue_rwaTBILL")}";
export const QUEUE_CREDIT = "${lc("RedemptionQueue_rwaCREDIT")}";
export const VAULT_EXPRESS = "${lc("CuratorVault_Express")}";
export const VAULT_PATIENT = "${lc("CuratorVault_Patient")}";
export const RWA_GATE_HOOK = "${lc("RWAGateHook")}";
export const FAUCET = "${lc("Faucet")}";
`;
writeFileSync(join(here, "../src/addresses.ts"), ts);
console.log("src/addresses.ts regenerated");
